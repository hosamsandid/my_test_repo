"use strict";

// Internal-API authentication for the orchestrator's :4002 surface (#1456,
// GOV-PLATFORM-2, `docs/governance-concept.md` §3.5).
//
// Until this landed, :4002 was reachable — unauthenticated — by anything on the
// container network, agent containers included. Every console-side authorization
// gate is therefore bypassable by an agent that talks to :4002 directly, which is
// why §3.5 calls this the highest-leverage control in the whole concept.
//
// This module is the PURE decision core: given a method, a URL and the request
// headers, it says who is calling and whether that caller may have the route. It
// does no fs, no network and no logging — `orchestrator.js` is its adapter, the
// same split as `flow-anomaly-detector.js` / `wake-agent.js`.
//
// ── The three token classes (§3.5) ──────────────────────────────────────────
//
//   console-proxy  A single opaque shared secret, `INTERNAL_API_TOKEN`, injected
//                  into the admin-console container and sent as a bearer header.
//                  Grants the FULL /internal/* surface, because the console has
//                  already applied its own per-user authorization before it
//                  proxies (that is what `admin-console/api/scope.js` is for).
//
//   agent          A per-agent token minted at `startAgentProcess` and baked into
//                  the container env like the PAT. Deterministic — it is an HMAC
//                  over the agent id, so a respawn re-mints the identical value
//                  and no state has to be kept. Valid ONLY for the agent-facing
//                  allowlist below, and (with one documented exception) only for
//                  the agent's own `:id`.
//
//   plugin-scope   §3.5's "signaler" class for external event sources, which had
//                  no subject after `POST /internal/bp-events` was deleted
//                  (#1961/#2005) and was therefore left unimplemented — a token
//                  class nothing can present is a hole with a name. The plugin
//                  system's first broker→orchestrator channel (`POST
//                  /internal/plugin-event`, Jira plan §4B) is that subject: a
//                  broker presents the HMAC scope token `plugin-scope-token.js`
//                  mints for it, signed with the plugin registry's shared secret
//                  (`/workspace/plugins/_secret`), and is allowlisted to EXACTLY
//                  that one route. The secret is a file, not an env var, so the
//                  adapter hands it in as a lazy getter (`pluginScopeSecret`)
//                  and this module stays fs-free.
//
// ── The enforcement ladder (§3.2) ───────────────────────────────────────────
//
//   observe   allow, but tag the would-be violation so an operator can inventory
//             every real caller before switching anything off. THE DEFAULT — a
//             stack upgrading into this release behaves exactly as before.
//   warn      allow + tag, louder (the adapter logs at warn level).
//   enforce   deny with 401/403.
//
// The decision is identical in all three modes; only `denied` differs. That is
// deliberate: the observe-mode log line is generated by the same predicate that
// will later reject, so the census cannot disagree with the enforcement.

const crypto = require("crypto");
const pluginScopeToken = require("./plugin-scope-token");
const { scopeIdFromGrantScope } = require("./plugin-scope");

const AUTH_MODES = ["observe", "warn", "enforce"];

// Wire format of a per-agent token. Three dot-separated fields so the split is
// unambiguous, and a version prefix so a future format change is detectable
// rather than silently mis-parsed (the `plugin-scope-token.js` shape).
const AGENT_TOKEN_PREFIX = "aeeagt1";
const AGENT_TOKEN_CONTEXT = "aee-internal-agent-v1:";

// Deriving the agent-token signing secret from the control-plane token means an
// operator sets ONE value. scrypt (one-way, deliberately expensive) is what makes
// that safe: an agent holds a token derived from the secret, never the secret,
// and can therefore not walk back to the control-plane token it would need to
// reach the rest of the surface.
const AGENT_SECRET_SALT = "aee-internal-agent-secret-v1";

// ── Configuration ───────────────────────────────────────────────────────────

// `fallback` is the mode an unset/invalid value lands on. It is a parameter,
// not a constant, because the safe default is deployment-dependent (#2459): a
// local compose stack falls back to `observe`, a non-local (kubernetes) one to
// `enforce`. A recognised rung is ALWAYS honoured verbatim — that is what keeps
// an operator's deliberate `INTERNAL_AUTH_MODE=observe` (an in-progress
// migration) from being silently overridden by the safer default.
function parseAuthMode(raw, fallback = "observe") {
  const v = String(raw || "").trim().toLowerCase();
  return AUTH_MODES.includes(v) ? v : fallback;
}

// Whether an explicit, recognised mode was configured (as opposed to unset or a
// typo). The safer default and the boot warning both key off this, so an
// operator who deliberately chose a rung is treated differently from one who
// left it unset.
function authModeExplicit(raw) {
  return AUTH_MODES.includes(String(raw || "").trim().toLowerCase());
}

// The deployment contexts where the safer `enforce` default applies (#2459).
// Keyed on the same runtime seam the spawner uses (`AEE_CONTAINER_RUNTIME`):
// `kubernetes` is the shared/production-style GKE deploy path (`deploy/k8s/`),
// while the local single-developer Podman Compose stack (`podman`/unset) keeps
// `observe` for developer convenience. The non-GKE-but-network-exposed Podman
// case is deliberately NOT covered here — it is the issue's open question,
// flagged for Product-Owner decision rather than guessed at.
function isNonLocalDeployment(env = {}) {
  return String(env.AEE_CONTAINER_RUNTIME || "").trim().toLowerCase() === "kubernetes";
}

// The control-plane token is the single operator knob; the agent signing secret
// is derived from it unless one is set explicitly. Returns a frozen descriptor so
// a caller cannot mutate the live config by accident.
//
// `pluginScopeSecret` (second arg) is the plugin registry's scope-token signing
// secret — a string, or a getter returning one. A getter is what the adapter
// passes, because the secret lives in a file that is created on first use:
// resolving the config at module load must not touch the fs, and a control-plane
// or agent caller must never need it (they are classified first).
function resolveInternalAuthConfig(env = {}, { pluginScopeSecret = null } = {}) {
  const controlPlaneToken = String(env.INTERNAL_API_TOKEN || "").trim();
  const explicitAgentSecret = String(env.INTERNAL_AGENT_TOKEN_SECRET || "").trim();
  const configured = Boolean(controlPlaneToken || explicitAgentSecret);
  const nonLocal = isNonLocalDeployment(env);
  // Safer default OUTSIDE local development (#2459). A non-local deployment with
  // the gate ARMED (a token configured) defaults to `enforce` when the operator
  // has not chosen a mode — so the GKE path stops shipping in silent log-only
  // mode without anyone setting `INTERNAL_AUTH_MODE`. Kept off the unconfigured
  // case on purpose: with no token the gate is inert anyway, and `enforce` there
  // would be refused at boot (`bootRefusal`) and kill the platform. The local
  // stack keeps `observe`. An explicit rung always wins (see `parseAuthMode`),
  // so a deliberate migration-window `observe` is never overridden.
  const defaultMode = (nonLocal && configured) ? "enforce" : "observe";
  const modeExplicit = authModeExplicit(env.INTERNAL_AUTH_MODE);
  const mode = parseAuthMode(env.INTERNAL_AUTH_MODE, defaultMode);
  const agentTokenSecret = explicitAgentSecret
    || (controlPlaneToken
      ? crypto.scryptSync(controlPlaneToken, AGENT_SECRET_SALT, 32).toString("hex")
      : "");
  return Object.freeze({
    mode,
    // `true` only when a recognised rung was set explicitly (not unset/typo).
    // The boot warning reads it to distinguish a deliberate `observe` from a
    // deployment that simply never chose one.
    modeExplicit,
    // `true` on the non-local (kubernetes) deploy path — see the boot warning.
    nonLocal,
    controlPlaneToken,
    agentTokenSecret,
    pluginScopeSecret,
    // With no control-plane token there is nothing to present and nothing to
    // mint, so the gate has to stay inert whatever the mode says. `configured`
    // is what the boot check reads to refuse an `enforce` that would lock every
    // caller out of the platform.
    configured,
  });
}

// A misconfiguration that would deny every request is refused at BOOT, where an
// operator sees it, rather than at the first request, where they see a dead
// platform. Returns an error string, or null when the config is coherent.
function bootRefusal(config) {
  if (config.mode === "enforce" && !config.configured) {
    return "INTERNAL_AUTH_MODE=enforce requires INTERNAL_API_TOKEN (or "
      + "INTERNAL_AGENT_TOKEN_SECRET) to be set — without a token every caller, "
      + "including the admin console, would be rejected.";
  }
  return null;
}

// #2459 AC3: a non-local deployment must not sit in log-only mode UNNOTICED.
// Returns a warning string when a non-local (kubernetes) deployment is not
// enforcing, or null. Two shapes, because the fix differs:
//   - unconfigured: the gate is inert (no token) — the operator has to arm it;
//     `enforce` is refused at boot until they do, so this is the actionable step.
//   - configured but observe/warn: violations are logged but NOT blocked. If the
//     operator set that explicitly it is likely a deliberate migration window
//     (legitimate, but still worth surfacing); if it defaulted there it should
//     not have — either way, name it so it does not go silent.
// The adapter logs this at warn level; it is never a boot refusal.
function nonLocalObserveWarning(config) {
  if (!config.nonLocal || config.mode === "enforce") return null;
  if (!config.configured) {
    return "internal-auth: non-local deployment with the :4002 gate INERT "
      + "(no INTERNAL_API_TOKEN) — every agent container can reach the control "
      + "plane unauthenticated. Set INTERNAL_API_TOKEN to arm it; this path then "
      + "defaults to enforce.";
  }
  const why = config.modeExplicit
    ? `INTERNAL_AUTH_MODE=${config.mode} is set explicitly`
    : `running in ${config.mode}`;
  return `internal-auth: non-local deployment is ${why}, not enforce — :4002 `
    + "violations are logged but NOT blocked. Move to INTERNAL_AUTH_MODE=enforce "
    + "once the observe log is quiet.";
}

// ── Per-agent tokens ────────────────────────────────────────────────────────

function agentSignature(agentId, secret) {
  return crypto
    .createHmac("sha256", secret)
    .update(`${AGENT_TOKEN_CONTEXT}${agentId}`)
    .digest("base64url");
}

// Deterministic: the same (agentId, secret) always yields the same token, which
// is what makes rotation free — `startAgentProcess` re-mints on every respawn and
// changing the secret invalidates every outstanding token at once (§3.5's
// "rotate via the existing respawn-on-credential-change path").
function mintAgentToken(agentId, secret) {
  if (!agentId || !secret) return null;
  const id = String(agentId);
  return `${AGENT_TOKEN_PREFIX}.${Buffer.from(id, "utf8").toString("base64url")}.${agentSignature(id, secret)}`;
}

// Returns the agent id the token attests to, or null. Constant-time on the
// signature compare; the length pre-check is what keeps `timingSafeEqual` from
// throwing on a malformed token.
function verifyAgentToken(token, secret) {
  if (!token || !secret || typeof token !== "string") return null;
  const parts = token.split(".");
  if (parts.length !== 3 || parts[0] !== AGENT_TOKEN_PREFIX) return null;
  let agentId;
  try {
    agentId = Buffer.from(parts[1], "base64url").toString("utf8");
  } catch {
    return null;
  }
  if (!agentId) return null;
  const expected = agentSignature(agentId, secret);
  const got = Buffer.from(parts[2]);
  const want = Buffer.from(expected);
  if (got.length !== want.length || !crypto.timingSafeEqual(got, want)) return null;
  return agentId;
}

function safeEqualStrings(a, b) {
  const x = Buffer.from(String(a));
  const y = Buffer.from(String(b));
  if (x.length !== y.length) return false;
  return crypto.timingSafeEqual(x, y);
}

// ── The agent-facing allowlist ──────────────────────────────────────────────
//
// Derived by reading every caller that runs INSIDE an agent container
// (`agent-image/scripts/`: agent-entrypoint.py, aee-wake, knowledge,
// usage, gh-as-agent) rather than from the prose list in §3.5 — the prose names
// "knowledge", "usage ingest" and "maintenance-mode read" as categories, and one
// of its four concrete paths (`/internal/agents/:id/claim`) no longer exists.
//
// `scope`:
//   'own'   the captured `:id` MUST equal the calling agent's own id.
//   'any'   the route carries no agent id (or its own authorization, below).
//   'peer'  the route legitimately names ANOTHER agent — see enqueue-pending.
const AGENT_ROUTES = [
  // Session + telemetry push (agent-entrypoint.py)
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/status$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/running-sessions$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/session-events$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/session-pointer$/, scope: "own" },

  // Usage ingest + the `usage` CLI's read-back
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/usage$/, scope: "own" },
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/usage\/summary$/, scope: "own" },

  // Knowledge (the `knowledge` CLI + the runtime's retrieval hook)
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/knowledge\/push$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/knowledge\/retrieval$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/knowledge\/nominate$/, scope: "own" },

  // Own configuration + room, re-read per invocation on a per-agent volume
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/config$/, scope: "own" },
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/dm-room$/, scope: "own" },

  // Self-managed triggers (the agent may edit its own triggers.json)
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/triggers$/, scope: "own" },
  { method: "PUT", pattern: /^\/internal\/agents\/([^/]+)\/triggers$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/triggers\/([^/]+)\/consumed$/, scope: "own" },

  // Pending queue drain
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/pending-drain$/, scope: "own" },
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/pending-drain-one$/, scope: "own" },

  // Team roster (#933 — who the loop verifier could be)
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/team-roster$/, scope: "own" },

  // Parent-ticket binding (#1383) — §3.5's `ticket*`
  { method: "GET", pattern: /^\/internal\/agents\/([^/]+)\/ticket$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/ticket$/, scope: "own" },
  { method: "DELETE", pattern: /^\/internal\/agents\/([^/]+)\/ticket$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/ticket\/children$/, scope: "own" },

  // Attributed git writes (gh-as-agent) — the orchestrator resolves the
  // credential, so `own` here is exactly what stops agent A pushing as agent B.
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/git\/push$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/git\/pr$/, scope: "own" },
  // Chat-attributed `gh` writes (#2559, the `gh` shim) — same reasoning.
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/github\/gh$/, scope: "own" },

  // Plugin run identity (#2562): the runner's per-container run key and its
  // run declarations. The handler additionally requires the agent's caller
  // token for the same :id.
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/run-key$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/runs$/, scope: "own" },
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/runs\/end$/, scope: "own" },

  // THE ONE CROSS-AGENT ROUTE. The loop verifier (#933) hands its verify request
  // to a SIBLING's queue, so `own` would break every loop with a `verify.agentId`
  // gate. Left as `peer` rather than silently narrowed; the route's own same-team
  // check is the named follow-up (the `wake-agent.js` precedent).
  { method: "POST", pattern: /^\/internal\/agents\/([^/]+)\/enqueue-pending$/, scope: "peer" },

  // Routes with no agent id in the path. Each carries its own integrity check:
  // wake-agent resolves + authorizes the target itself, and
  // loop-verify/verdict is keyed on an opaque one-shot verify token.
  // (POST /internal/flow-emit was removed with the internal transport, #2578.)
  { method: "POST", pattern: /^\/internal\/wake-agent$/, scope: "any" },
  { method: "GET", pattern: /^\/internal\/loop-verify\/verdict$/, scope: "any" },
  { method: "POST", pattern: /^\/internal\/loop-verify\/verdict$/, scope: "any" },

  // Maintenance-mode read — every scheduler checks it before firing.
  { method: "GET", pattern: /^\/internal\/maintenance-mode$/, scope: "any" },
];

// ── The plugin-facing allowlist ─────────────────────────────────────────────
//
// A broker sidecar holds a scope token for ONE (pluginId, scopeId) and may use
// it for waking the agents that plugin is granted to in that scope, and — with
// its reserved grant token only — for asking whose credential an agent CLI call
// may use (below). The route re-verifies the token itself to derive
// {pluginId, scopeId} for the fan-out, so this gate is the first line and the
// handler the second. Everything else — the credential push, the team roster,
// wake-agent — is a control-plane concern and stays refused.
const PLUGIN_SCOPE_ROUTES = [
  { method: "POST", pattern: /^\/internal\/plugin-event$/ },
  // #2562: a broker asks which credential ONE agent CLI call may use. Only with
  // its reserved `_grant-<scopeId>` token: the plain scope token is also held by
  // every granted agent, and this route returns a person's secret.
  { method: "POST", pattern: /^\/internal\/plugin-credential-grant$/, grantScope: true },
];

// Strip the query string and decode each path segment, so an allowlist entry
// cannot be side-stepped with `%2f`-style encoding or a trailing `?x=1`.
function normalizePath(url) {
  let pathname;
  try {
    pathname = new URL(String(url || ""), "http://internal").pathname;
  } catch {
    return null;
  }
  try {
    return pathname
      .split("/")
      .map((seg) => decodeURIComponent(seg))
      .join("/");
  } catch {
    return null; // undecodable escape — treat as unmatched, never as allowed
  }
}

// The rule this (method, path) falls under for an agent caller, or null when the
// route is not agent-facing at all.
function agentRouteRule(method, pathname) {
  const m = String(method || "").toUpperCase();
  for (const route of AGENT_ROUTES) {
    if (route.method !== m) continue;
    const match = pathname.match(route.pattern);
    if (match) return { ...route, params: match.slice(1) };
  }
  return null;
}

function pluginRouteRule(method, pathname) {
  const m = String(method || "").toUpperCase();
  for (const route of PLUGIN_SCOPE_ROUTES) {
    if (route.method !== m) continue;
    if (pathname.match(route.pattern)) return route;
  }
  return null;
}

// The plugin secret is resolved on demand and only after the control-plane and
// agent classes have been ruled out. A getter that throws (registry dir not
// mounted, fs error) yields "no secret" — the token is then anonymous, never
// allowed by accident.
function resolvePluginScopeSecret(config) {
  const src = config.pluginScopeSecret;
  if (!src) return "";
  try {
    const value = typeof src === "function" ? src() : src;
    return typeof value === "string" ? value.trim() : "";
  } catch {
    return "";
  }
}

// ── The decision ────────────────────────────────────────────────────────────

function classifyCaller(headers = {}, config) {
  const raw = headers.authorization || headers.Authorization || "";
  const value = Array.isArray(raw) ? raw[0] : raw;
  const match = String(value || "").match(/^Bearer\s+(.+)$/i);
  if (!match) return { kind: "anonymous", agentId: null };
  const presented = match[1].trim();
  if (config.controlPlaneToken && safeEqualStrings(presented, config.controlPlaneToken)) {
    return { kind: "console-proxy", agentId: null };
  }
  const agentId = verifyAgentToken(presented, config.agentTokenSecret);
  if (agentId) return { kind: "agent", agentId };
  const pluginSecret = resolvePluginScopeSecret(config);
  if (pluginSecret) {
    let scope = null;
    try { scope = pluginScopeToken.verify(presented, pluginSecret); } catch { scope = null; }
    if (scope && scope.pluginId && scope.scopeId) {
      return { kind: "plugin-scope", agentId: null, pluginId: scope.pluginId, scopeId: scope.scopeId };
    }
  }
  return { kind: "anonymous", agentId: null };
}

/**
 * The whole gate, as one pure function.
 *
 * Returns `{ callerKind, agentId, allowed, denied, status, reason, mode }`.
 * `allowed` is the verdict; `denied` is whether this MODE acts on it — the two
 * are separate so an observe-mode run produces exactly the audit line an
 * enforce-mode run would deny on.
 */
function decideInternalAuth({ method, url, headers = {}, config }) {
  const mode = config.mode;
  const pathname = normalizePath(url);

  // Gate inert with nothing configured: no token exists, so no caller could
  // present one and every request would be "anonymous". A stack that has not
  // opted in behaves exactly as it did before this landed.
  if (!config.configured) {
    return {
      callerKind: "unconfigured", agentId: null, allowed: true, denied: false,
      status: 0, reason: "internal-auth-not-configured", mode, pathname,
    };
  }

  const caller = classifyCaller(headers, config);
  const enforcing = mode === "enforce";

  if (caller.kind === "console-proxy") {
    return {
      callerKind: "console-proxy", agentId: null, allowed: true, denied: false,
      status: 0, reason: "control-plane-token", mode, pathname,
    };
  }

  if (caller.kind === "anonymous") {
    return {
      callerKind: "anonymous", agentId: null, allowed: false, denied: enforcing,
      status: 401, reason: "no-valid-internal-token", mode, pathname,
    };
  }

  // A plugin broker presented a valid scope token — one route, nothing else.
  if (caller.kind === "plugin-scope") {
    const base = {
      callerKind: "plugin-scope", agentId: null,
      pluginId: caller.pluginId, scopeId: caller.scopeId, mode, pathname,
    };
    if (pathname === null) {
      return { ...base, allowed: false, denied: enforcing, status: 403, reason: "unparseable-path" };
    }
    const pluginRule = pluginRouteRule(method, pathname);
    if (!pluginRule) {
      return { ...base, allowed: false, denied: enforcing, status: 403, reason: "route-not-plugin-facing" };
    }
    if (pluginRule.grantScope && !scopeIdFromGrantScope(caller.scopeId)) {
      return { ...base, allowed: false, denied: enforcing, status: 403, reason: "grant-token-required" };
    }
    return { ...base, allowed: true, denied: false, status: 0, reason: "plugin-allowlist" };
  }

  // An agent presented a valid token — now the allowlist decides.
  if (pathname === null) {
    return {
      callerKind: "agent", agentId: caller.agentId, allowed: false, denied: enforcing,
      status: 403, reason: "unparseable-path", mode, pathname,
    };
  }
  const rule = agentRouteRule(method, pathname);
  if (!rule) {
    return {
      callerKind: "agent", agentId: caller.agentId, allowed: false, denied: enforcing,
      status: 403, reason: "route-not-agent-facing", mode, pathname,
    };
  }
  if (rule.scope === "own" && rule.params[0] !== caller.agentId) {
    return {
      callerKind: "agent", agentId: caller.agentId, allowed: false, denied: enforcing,
      status: 403, reason: "cross-agent-id", mode, pathname,
    };
  }
  return {
    callerKind: "agent", agentId: caller.agentId, allowed: true, denied: false,
    status: 0, reason: `agent-allowlist:${rule.scope}`, mode, pathname,
  };
}

// One line per would-be violation, so the observe week produces a grep-able
// census. Shape mirrors the audit fields GOV-PLATFORM-3 will persist.
function describeDecision(decision, { method } = {}) {
  const subject = decision.agentId
    || (decision.pluginId ? `${decision.pluginId}/${decision.scopeId}` : "");
  return `[internal-auth] mode=${decision.mode} caller=${decision.callerKind}`
    + `${subject ? `(${subject})` : ""}`
    + ` ${String(method || "").toUpperCase()} ${decision.pathname || "?"}`
    + ` verdict=${decision.allowed ? "allow" : (decision.denied ? "deny" : "would-deny")}`
    + ` reason=${decision.reason}`;
}

