'use strict';

// ─── Extract an Agent Template from a live agent (#1509) ────────────────────
//
// The inverse of team materialisation: a proven live agent (a standalone chat
// agent or an individual team member) is snapshotted into a reusable, TEAM-
// NEUTRAL Agent Template so future agents can be created from it.
//
// This module is PURE (no filesystem, no network) so it is unit-testable
// without a running stack — api.js reads the live config / effective prompt /
// triggers off disk and hands the resolved values in. The mapping rules
// (AC-5/6/7) live here:
//   - effective prompt  → promptTemplate (a fully-resolved LITERAL snapshot;
//                          buildMemberFromTemplate + the RoleTemplates editor
//                          both read `promptTemplate`)
//   - skills[]          → skills[]
//   - sessionPolicy     → sessionPolicy
//   - the trigger set   → inline triggers[] ONLY when opted in
//   - runtime/identity + team-composition fields are NEVER carried: the
//     template is built from a whitelist, so `userId`/`token`/`environmentId`/
//     `teamId`/`enabled`/`role` and stage/port/label-suffix/parent metadata
//     simply have no path into the output.

const store = require('./agent-templates-store');

const { TRIGGER_TYPES, PATTERN_ROLES } = store;

function isNonEmptyString(v) {
  return typeof v === 'string' && v.trim() !== '';
}

// Derive a slug-valid template id (agent-templates-store.TEMPLATE_ID_RE:
// lowercase letters/digits/hyphens, not leading with a hyphen) from an agent
// id (which also allows `_` and `.`).
function slugifyTemplateId(s) {
  const base = String(s == null ? '' : s)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-') // any run of non-alnum → single hyphen
    .replace(/-{2,}/g, '-')
    .replace(/^-+/, '')
    .replace(/-+$/, '');
  return base || 'agent-template';
}

/**
 * Suggest a template id derived from the source agent id, unique across the
 * supplied set of existing ids (both tiers). Server-side collision handling
 * (409) is still the source of truth — this is just a friendlier default.
 */
function suggestTemplateId(sourceId, existingIds) {
  const set = existingIds instanceof Set ? existingIds : new Set(existingIds || []);
  const base = slugifyTemplateId(sourceId);
  if (!set.has(base)) return base;
  let n = 2;
  while (set.has(`${base}-${n}`)) n += 1;
  return `${base}-${n}`;
}

// A source agent reads as "reactive" (event-driven) when it runs fresh per
// trigger or listens for GitHub/webhook events; otherwise it is a "chat"
// companion. Used only to PRE-FILL the editable category/patternRole (AC-2).
function isReactiveAgent(cfg = {}, triggers = []) {
  if (cfg && cfg.sessionPolicy === 'per-invocation') return true;
  const tl = Array.isArray(triggers) ? triggers : [];
  return tl.some(tr => tr && (tr.type === 'github-event' || tr.type === 'http'));
}

function inferTemplateCategory(cfg, triggers) {
  return isReactiveAgent(cfg, triggers) ? 'reactive' : 'chat';
}

function inferPatternRole(cfg = {}, category) {
  if (cfg && PATTERN_ROLES.includes(cfg.patternRole)) return cfg.patternRole;
  return category === 'reactive' ? 'author' : 'companion';
}

/**
 * Reduce a live runtime trigger to the team-neutral inline shape a template
 * carries. Returns null for triggers that must NOT travel:
 *   - types the template store does not accept (e.g. `loop`)
 *   - derived flow-wiring triggers (`dataFlow` / `channel`), which reference
 *     concrete team members and are re-generated by reconciliation — pure
 *     team-composition metadata (AC-7).
 * Runtime/team-specific fields (repo, secret, createdAt/activatedAt, claim,
 * sources, transport) are dropped; the runtime `prompt` maps to the template's
 * `promptTemplate`.
 */
function sanitizeTemplateTrigger(tr) {
  if (!tr || typeof tr !== 'object' || Array.isArray(tr)) return null;
  if (!TRIGGER_TYPES.has(tr.type)) return null;
  if (!isNonEmptyString(tr.id)) return null;
  if (tr.dataFlow === true || tr.channel === true) return null;

  const out = { id: tr.id, type: tr.type };
  if (tr.enabled === false) out.enabled = false;
  if (tr.intrinsic === true) out.intrinsic = true;
  if (isNonEmptyString(tr.description)) out.description = tr.description;

  const promptText = isNonEmptyString(tr.promptTemplate) ? tr.promptTemplate
    : isNonEmptyString(tr.prompt) ? tr.prompt
      : '';
  if (promptText) out.promptTemplate = promptText;

  if (tr.type === 'cron' && isNonEmptyString(tr.cron)) out.cron = tr.cron;
  if (tr.type === 'once' && isNonEmptyString(tr.at)) out.at = tr.at;
  if (tr.type === 'github-event') {
    if (Array.isArray(tr.events)) out.events = tr.events.filter(e => typeof e === 'string');
    if (isNonEmptyString(tr.labelFilter)) out.labelFilter = tr.labelFilter;
  }
  if (isNonEmptyString(tr.preCheckScript)) out.preCheckScript = tr.preCheckScript;
  if (tr.preCheckEnv && typeof tr.preCheckEnv === 'object' && !Array.isArray(tr.preCheckEnv)) {
    out.preCheckEnv = { ...tr.preCheckEnv };
  }
  return out;
}

/**
 * Build the team-neutral template object from resolved source values. Pure;
 * never throws. The caller validates the result through
 * agent-templates-store.validateTemplate before persisting.
 *
 * @param {object} source
 * @param {string}  source.id             - the (slug-valid) template id
 * @param {string}  source.displayName
 * @param {string}  [source.description]
 * @param {string}  [source.category]     - 'chat' | 'reactive' | 'pattern'
 * @param {string}  [source.patternRole]
 * @param {string}  source.prompt         - the agent's EFFECTIVE system prompt
 * @param {string[]}[source.skills]
 * @param {string}  [source.sessionPolicy]
 * @param {object[]}[source.triggers]     - the agent's live triggers
 * @param {boolean} [source.includeTriggers]
 * @returns {object} the template object (templateSchemaVersion: 1)
 */
function buildExtractedTemplate(source = {}) {
  const {
    id, displayName, description, category, patternRole,
    prompt, skills, sessionPolicy, triggers, includeTriggers,
  } = source;

  const t = {
    templateSchemaVersion: 1,
    id,
    displayName,
  };
  if (isNonEmptyString(description)) t.description = description.trim();
  if (isNonEmptyString(category)) t.category = category;
  if (isNonEmptyString(patternRole)) t.patternRole = patternRole;

  // The effective prompt is a fully-resolved literal. It lands in
  // `promptTemplate` (never a `{{var}}` template here) so both the template
  // editor and buildMemberFromTemplate reproduce it verbatim on instantiation.
  t.promptTemplate = typeof prompt === 'string' ? prompt : '';
  t.skills = Array.isArray(skills) ? skills.filter(s => typeof s === 'string') : [];
  t.sessionPolicy = sessionPolicy === 'per-invocation' ? 'per-invocation' : 'persistent';

  if (includeTriggers) {
    const inline = (Array.isArray(triggers) ? triggers : [])
      .map(sanitizeTemplateTrigger)
      .filter(Boolean);
    if (inline.length) t.triggers = inline;
  }
  return t;
}

module.exports = {
  slugifyTemplateId,
  suggestTemplateId,
  isReactiveAgent,
  inferTemplateCategory,
  inferPatternRole,
  sanitizeTemplateTrigger,
  buildExtractedTemplate,
};
