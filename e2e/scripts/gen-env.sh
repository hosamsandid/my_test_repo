#!/bin/bash
set -euo pipefail

# Generate .env.e2e at the repo root for the disposable `aee-e2e` stack
# (#666, docs/e2e-testing-concept.md §5). Fixed admin credentials + isolated
# ports/project so the e2e stack never collides with the developer's normal
# `agent-studio` stack. The LLM proxy vars point at a dead address — the fake
# `claude` shim (AEE_FAKE_CLAUDE=1) is what actually answers, so no real
# endpoint is ever reached.
#
# Idempotent: MATRIX_ACCESS_TOKEN / CONDUWUIT_ADMIN_ROOM (written back by
# setup.sh after the Matrix bootstrap) are carried forward from an existing
# .env.e2e so re-running the generator mid-lifecycle doesn't wipe them.

REPO_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ENV_FILE="${REPO_ROOT}/.env.e2e"

# Carry forward bootstrap-written values if a prior .env.e2e exists.
prev_val() {
  [ -f "$ENV_FILE" ] || return 0
  grep -E "^$1=" "$ENV_FILE" | tail -n1 | cut -d= -f2- || true
}
PREV_TOKEN="$(prev_val MATRIX_ACCESS_TOKEN)"
PREV_ROOM="$(prev_val CONDUWUIT_ADMIN_ROOM)"

# Rootless podman socket: honour an explicit override (CI sets this), else the
# Linux rootless default for the current uid.
DEFAULT_SOCK="/run/user/$(id -u)/podman/podman.sock"
SOCK="${PODMAN_HOST_SOCKET:-$DEFAULT_SOCK}"

cat > "$ENV_FILE" <<EOF
# GENERATED by e2e/scripts/gen-env.sh — do not edit by hand.
# Disposable E2E stack config (#666). Isolated from the dev stack by project
# name + dedicated ports. Regenerate with: make e2e-env (or gen-env.sh).

# --- Isolation ---
COMPOSE_PROJECT_NAME=aee-e2e
AEE_INSTANCE_ID=e2e

# --- Ports (offset from the dev defaults so both stacks can run at once) ---
ADMIN_PORT=4010
CONDUWUIT_PORT=8449
HOOK_PORT=4013
# #710: host-published fake-github port so the Playwright runner can act as the
# human on GitHub + assert against fake-github's inspection endpoint.
FAKE_GITHUB_PORT=4014

# --- LLM: stubbed at the claude-binary seam ---
AEE_FAKE_CLAUDE=1
# #711: IBAN-story journey — fake-claude reply fixtures + role playbooks (baked
# into the agent image at /opt/ace/e2e/), and a tight GitHub poll cadence so the
# label chain (issue.labeled→Developer→PR.labeled→Reviewer) fits the test budget.
AEE_FAKE_CLAUDE_FIXTURES=/opt/ace/e2e/fixtures/iban-story.fixtures.json
AEE_FAKE_CLAUDE_PLAYBOOKS=/opt/ace/e2e/fixtures/playbooks
AEE_GITHUB_POLL_INTERVAL_MS=2000
ANTHROPIC_BASE_URL=http://127.0.0.1:1
ANTHROPIC_AUTH_TOKEN=e2e-dead-token
ANTHROPIC_DEFAULT_SONNET_MODEL=claude-fake-e2e
ANTHROPIC_DEFAULT_HAIKU_MODEL=claude-fake-e2e
CLAUDE_CODE_DISABLE_EXPERIMENTAL_BETAS=1

# --- Fake GitHub (#710, journey-spec §6.1) ---
# Point the poller + wizard GitHub-API calls at the in-stack fake-github
# service. Absent ⇒ api.github.com (production behaviour). Server-side prompt
# generation (POST /api/agent-prompt/generate) uses a Model Provider that
# stack-up.sh registers explicitly, pointing at fake-github's mock /v1/messages
# (§6.3) — NOT the dead ANTHROPIC_BASE_URL above.
GITHUB_API_BASE=http://fake-github
MOCK_LLM_BASE_URL=http://fake-github

# --- Pinned Matrix server (no :latest drift) ---
CONDUWUIT_IMAGE=ghcr.io/continuwuity/continuwuity:v0.5.5

# --- Admin (fixed seed values so specs can log in deterministically) ---
# Since #2059 these are consumed once at first boot to create a real
# System-Admin user record; the specs then sign in against that record.
ADMIN_USER=admin
ADMIN_USERNAME=admin
ADMIN_PASSWORD=e2e-admin-pass
AUTH_SESSION_SECRET=e2e-fixed-session-secret
AUTH_COOKIE_SECURE=

# --- Podman socket ---
PODMAN_HOST_SOCKET=${SOCK}

# --- Populated by orchestrator/setup.sh (Matrix bootstrap) ---
MATRIX_ACCESS_TOKEN=${PREV_TOKEN}
CONDUWUIT_ADMIN_ROOM=${PREV_ROOM}
EOF

echo "Wrote ${ENV_FILE}"
