// Journey → Markdown renderer (docs/journey-spec-concept.md §3.2 item 1, #707).
//
// Pure: given a validated journey doc, its run manifest and a few path hints, it
// returns the Markdown for one user-guide page — narrative paragraphs interleaved
// with the captured screenshots, in journey order. No filesystem, no date/git
// access: all provenance (commit SHA, run date) is read from the manifest, so the
// same inputs always render the same bytes. That is what makes the generated-doc
// no-diff check (§3.2, "reviewed like any other diff when regenerated") and the
// podman-free golden test possible.
'use strict';

const path = require('path');

// Filename for a journey's page: `<order>-<id>.md` (§3.2). Order is zero-padded
// to two digits so the files sort lexically the same way the runner sorts them
// numerically (10-, 20-, …) — a single-digit order would otherwise sort after 10.
function pageFileName(journey) {
  const order = String(journey.order ?? 0).padStart(2, '0');
  return `${order}-${journey.id}.md`;
}

// Directory (relative to the output root) that a journey's screenshots are copied
// into, so a generated page and its images travel together as one artifact bundle.
function assetDirFor(journey) {
  return path.posix.join('assets', journey.id);
}

// Build the stepId → screenshot-file lookup from a manifest. The runner records a
// capture under its `screenshot` name (runner.js passes `step.screenshot` as the
// recorder stepId), so a journey step's `screenshot: <name>` matches manifest
// entry `stepId === <name>`.
function screenshotIndex(manifest) {
  const idx = new Map();
  for (const shot of (manifest && manifest.screenshots) || []) {
    idx.set(shot.stepId, shot.file);
  }
  return idx;
}

// Normalise a YAML block-scalar narrative into clean Markdown paragraphs: trim
// outer blank lines and collapse runs of blank lines to a single separator, so
// the paragraph breaks the author wrote survive verbatim without stray blanks.
function renderNarrative(narrative) {
  return String(narrative)
    .replace(/\r\n/g, '\n')
    .split(/\n{2,}/)
    .map((para) => para.trim())
    .filter(Boolean)
    .join('\n\n');
}

// The generated-doc header (§3.2). HTML comments: invisible in the rendered guide
// but present in source, marking the page as generated (guards hand edits) and
// carrying the source journey, commit SHA and run date for provenance.
function renderHeader({ sourcePath, commitSha, timestamp }) {
  return [
    '<!-- @generated by e2e/docgen — DO NOT EDIT BY HAND. Regenerate with: make docs-journeys -->',
    `<!-- source: ${sourcePath} · commit: ${commitSha || 'unknown'} · generated: ${timestamp || 'unknown'} -->`,
  ].join('\n');
}

// Render one journey page. `manifest` may be null (no green run captured this
// journey yet) — narrative still renders; screenshot steps simply omit the image.
// `sourcePath` is the repo-relative path of the journey YAML (for the header).
function renderJourneyPage(journey, manifest, { sourcePath, assetDir } = {}) {
  const shots = screenshotIndex(manifest);
  const dir = assetDir || assetDirFor(journey);
  const parts = [];

  parts.push(renderHeader({
    sourcePath: sourcePath || `e2e/journeys/${journey.id}.yaml`,
    commitSha: manifest && manifest.commitSha,
    timestamp: manifest && manifest.timestamp,
  }));
  parts.push(`# ${journey.title}`);

  for (const step of journey.steps || []) {
    if (step.narrative) parts.push(renderNarrative(step.narrative));

    // A named capture point renders as an image — but only if the run actually
    // produced it (a step whose screenshot never captured, e.g. journey not yet
    // run, is silently skipped rather than emitting a broken image link).
    if (step.screenshot && shots.has(step.screenshot)) {
      const rel = path.posix.join(dir, shots.get(step.screenshot));
      parts.push(`![${step.id || step.screenshot}](${rel})`);
    }

    // narrative-only steps may carry a static diagram asset (§2.1 `visual`).
    if (step.visual) {
      parts.push(`![${step.id || 'diagram'}](${step.visual})`);
    }
  }

  return `${parts.join('\n\n')}\n`;
}

module.exports = {
  renderJourneyPage,
  renderNarrative,
  renderHeader,
  pageFileName,
  assetDirFor,
  screenshotIndex,
};
